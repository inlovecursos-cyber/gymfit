
package com.ginasio.repository;

import com.ginasio.model.Agendamento;
import jakarta.annotation.PostConstruct;
import jakarta.annotation.Resource;
import jakarta.enterprise.context.ApplicationScoped;

import javax.sql.DataSource;
import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.Statement;
import java.sql.SQLException;
import java.util.ArrayList;
import java.util.List;

@ApplicationScoped
public class AgendamentoRepository {

    @Resource(lookup = "jdbc/GymFitDB")
    private DataSource dataSource;

    @PostConstruct
    public void iniciar() {
        criarTabela();
    }

    public void criarTabela() {
        String sql = """
            CREATE TABLE IF NOT EXISTS agendamentos (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                nome VARCHAR(150) NOT NULL,
                atividade VARCHAR(100) NOT NULL,
                data_aula DATE NOT NULL,
                hora TIME NOT NULL
            )
            """;

        try (Connection ligacao = dataSource.getConnection();
             Statement comando = ligacao.createStatement()) {

            comando.executeUpdate(sql);

        } catch (SQLException erro) {
            throw new RuntimeException(
                "Erro ao criar a tabela de agendamentos.", erro
            );
        }
    }

    public Agendamento guardar(Agendamento agendamento) {
        String sql = """
            INSERT INTO agendamentos (nome, atividade, data_aula, hora)
            VALUES (?, ?, ?, ?)
            """;

        try (Connection ligacao = dataSource.getConnection();
             PreparedStatement comando = ligacao.prepareStatement(
                 sql, Statement.RETURN_GENERATED_KEYS)) {

            comando.setString(1, agendamento.getNome());
            comando.setString(2, agendamento.getAtividade());
            comando.setDate(
                3, java.sql.Date.valueOf(agendamento.getData())
            );
            comando.setTime(
                4, java.sql.Time.valueOf(agendamento.getHora() + ":00")
            );

            comando.executeUpdate();

            try (ResultSet chaves = comando.getGeneratedKeys()) {
                if (chaves.next()) {
                    agendamento.setId(chaves.getLong(1));
                }
            }

            return agendamento;

        } catch (SQLException erro) {
            throw new RuntimeException(
                "Erro ao guardar o agendamento.", erro
            );
        }
    }

    public List<Agendamento> listarTodos() {
        List<Agendamento> lista = new ArrayList<>();

        String sql = """
            SELECT id, nome, atividade, data_aula, hora
            FROM agendamentos
            ORDER BY data_aula, hora
            """;

        try (Connection ligacao = dataSource.getConnection();
             PreparedStatement comando = ligacao.prepareStatement(sql);
             ResultSet resultados = comando.executeQuery()) {

            while (resultados.next()) {
                lista.add(new Agendamento(
                    resultados.getLong("id"),
                    resultados.getString("nome"),
                    resultados.getString("atividade"),
                    resultados.getDate("data_aula").toString(),
                    resultados.getTime("hora").toString().substring(0, 5)
                ));
            }

        } catch (SQLException erro) {
            throw new RuntimeException(
                "Erro ao consultar os agendamentos.", erro
            );
        }

        return lista;
    }

    public boolean eliminar(Long id) {
        String sql = "DELETE FROM agendamentos WHERE id = ?";

        try (Connection ligacao = dataSource.getConnection();
             PreparedStatement comando = ligacao.prepareStatement(sql)) {

            comando.setLong(1, id);

            return comando.executeUpdate() > 0;

        } catch (SQLException erro) {
            throw new RuntimeException(
                "Erro ao eliminar o agendamento.", erro
            );
        }
    }
}